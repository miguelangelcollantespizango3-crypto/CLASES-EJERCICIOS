# 8. Promedio de calificaciones
# Crea tres variables con notas de un estudiante (números decimales).
# Calcula el promedio de las tres notas.
# Imprime el resultado con un mensaje descriptivo.

nota1 = 14.5
nota2 = 16.0
nota3 = 19.0

promedio = (nota1 + nota2 + nota3) / 3
print(f"El promedio del estudiante es: {promedio:.2f}")